//Do While Loop:
#include <iostream>
using namespace std;
int main()
{
cout<<"Standard while Loop\n";
int i=1;
do
{
cout<<i<<endl;
i++;
}while(i<5);
cout<<"Do-while Loop without initialization\n";
int j;
do
{
cout<<j<<endl;
j++;
}while(j<5);
cout<<"Do-while Loop without incr/decr\n";
int l=3;
do
{
cout<<l<<endl;
}while(l<5);
return 0;
}

