//While Loop:
#include <iostream>
using namespace std;
int main()
{
cout<<"Standard while Loop\n";
int i=1;
while(i<5)
{
cout<<i<<endl;
i++;
}
cout<<"while Loop without initialization\n";
int j;
while(j<5)
{
cout<<j<<endl;
j++;
}
cout<<"while Loop without incr/decr\n";
int l=3;
while(l<5)
{
cout<<l<<endl;
}
return 0;
}

